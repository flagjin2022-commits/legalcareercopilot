function interviewQuestion(
  id: string,
  type: InterviewQuestion["type"],
  ...args:
    | [InterviewQuestion["probability"], string, string[], string, string[], InterviewAnswerGuidance?]
    | [string, string[], string, string[], InterviewAnswerGuidance?]
): InterviewQuestion {
  const hasProbability = args[0] === "high" || args[0] === "medium";
  const probability: InterviewQuestion["probability"] = hasProbability
    ? (args[0] as InterviewQuestion["probability"])
    : "medium";
  const offset = hasProbability ? 1 : 0;
  const question = args[offset] as string;
  const focusPoints = args[offset + 1] as string[];
  const suggestedExperience = args[offset + 2] as string;
  const followUpQuestions = args[offset + 3] as string[];
  const answerGuidance =
    (args[offset + 4] as InterviewAnswerGuidance | undefined) ??
    mockAnswerGuidance[id] ?? {
      missingFacts: ["对应的真实经历背景", "本人具体动作", "法律判断过程", "工作产出", "最终用途或结果"],
    };

  return {
    id,
    type,
    probability,
    question,
    focusPoints,
    suggestedExperience,
    sourceExperience: suggestedExperience,
    testedSkill: focusPoints[0] ?? "岗位核心能力",
    professionalExtension: focusPoints.slice(1).join("、") || "结合岗位专业场景展开",
    followUpQuestions,
    answerGuidance,
  };
}

