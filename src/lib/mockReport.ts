function createGeneralSkills(
  assessments: Record<GeneralSkillId, GeneralSkillAssessment>,
): GeneralSkill[] {
  return (Object.keys(generalSkillCatalog) as GeneralSkillId[]).map((id) => {
    const assessment = assessments[id];
    return {
      ...generalSkillCatalog[id],
      jdRequirement: assessment.requiredScore,
      resumeEvidenceScore: assessment.score,
      evidenceLevel: assessment.score === null
        ? "insufficient"
        : assessment.score >= 80
          ? "direct"
          : assessment.score >= 65
            ? "transferable"
            : "foundational",
      evidenceSources: assessment.experienceEvidence ? [assessment.experienceEvidence] : [],
      weight: assessment.weight,
      jdMatchBasis: assessment.jdMatchBasis,
      experienceEvidence: assessment.experienceEvidence,
    };
  });
}

